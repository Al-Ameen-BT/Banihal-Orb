import { Pool, type PoolClient } from 'pg';
import cuid from 'cuid';
import { env } from './env';
// Reuse the tenant AsyncLocalStorage that already exists so Prisma-based and
// pg-based modules read the SAME tenant context during the migration. When Prisma
// is removed, the store's definition moves here and database.ts is deleted.
import { customerContext } from './database';

// ─── Connection pool (main `b2b` database) ───────────────────────────────────
export const pool = new Pool({ connectionString: env.DATABASE_URL, max: 10 });

// ─── Client-side defaults Prisma used to provide ─────────────────────────────
// `@default(cuid())` and `@updatedAt` were generated by the Prisma client, NOT by
// Postgres — so every raw INSERT must supply `id` (+ `updatedAt` where the model
// has one), and every UPDATE must refresh `updatedAt`. `createdAt` keeps its DB
// default (CURRENT_TIMESTAMP) and can be omitted.
export const newId = (): string => cuid();

// ─── Tenant context (fail-closed) ────────────────────────────────────────────
// Every tenant-scoped query must be filtered by this id. currentTenantId() throws
// when no context is set, so a scoped query can never accidentally run un-scoped.
export function currentTenantId(): string {
  const id = customerContext.getStore()?.customerId;
  if (!id) throw Object.assign(new Error('Tenant context is required for this query'), { status: 500, code: 'TENANT_CONTEXT_MISSING' });
  return id;
}
export const optionalTenantId = (): string | undefined => customerContext.getStore()?.customerId;

// ─── Low-level query helpers ─────────────────────────────────────────────────
export async function query<T = Record<string, unknown>>(text: string, params: readonly unknown[] = []): Promise<T[]> {
  const res = await pool.query(text, params as unknown[]);
  return res.rows as T[];
}
export async function queryOne<T = Record<string, unknown>>(text: string, params: readonly unknown[] = []): Promise<T | null> {
  const rows = await query<T>(text, params);
  return rows[0] ?? null;
}
// Run a write; returns the affected row count.
export async function execute(text: string, params: readonly unknown[] = []): Promise<number> {
  const res = await pool.query(text, params as unknown[]);
  return res.rowCount ?? 0;
}
// Transaction: all queries inside `fn` run on one client, committed or rolled back.
export async function transaction<T>(fn: (client: PoolClient) => Promise<T>): Promise<T> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

// ─── SQL builders ────────────────────────────────────────────────────────────
// Quote an identifier (table/column) for interpolation into SQL text. Only ever
// called with developer-provided constants, never user input.
export const ident = (name: string): string => `"${name.replace(/"/g, '""')}"`;

// Build a parameterized `SET a=$n, b=$n+1, "updatedAt"=$n+2` clause from a partial
// object, appending updatedAt=now() when `touchUpdatedAt` (the default). Returns
// the SQL fragment, the ordered params, and the next placeholder index.
export function buildSet(
  data: Record<string, unknown>,
  startIndex = 1,
  touchUpdatedAt = true,
): { sql: string; params: unknown[]; nextIndex: number } {
  const cols: string[] = [];
  const params: unknown[] = [];
  let i = startIndex;
  for (const [k, v] of Object.entries(data)) {
    if (v === undefined) continue; // skip absent fields (partial update)
    cols.push(`${ident(k)} = $${i++}`);
    params.push(v);
  }
  if (touchUpdatedAt) {
    cols.push(`${ident('updatedAt')} = $${i++}`);
    params.push(new Date());
  }
  return { sql: cols.join(', '), params, nextIndex: i };
}

// ─── Strict tenant-scoped access ─────────────────────────────────────────────
// The safety net that replaces Prisma's auto-injected `customerId` filter. Every
// helper here forces `"customerId" = <current tenant>` into the query, so a
// tenant-scoped read/write cannot forget its org filter. Use these for any table
// that has a `customerId` column; use the raw helpers above for global tables
// (customers, User, RefreshToken, …) and for explicit-id lookups.
export const scoped = {
  // SELECT <columns> FROM <table> WHERE (<where>) AND customerId=<tenant> [ORDER BY ...]
  async findMany<T = Record<string, unknown>>(
    table: string,
    opts: { columns?: string; where?: string; params?: readonly unknown[]; orderBy?: string; limit?: number } = {},
  ): Promise<T[]> {
    const tenant = currentTenantId();
    const params = [...(opts.params ?? [])];
    const tenantIdx = params.length + 1;
    params.push(tenant);
    const where = opts.where ? `(${opts.where}) AND ${ident('customerId')} = $${tenantIdx}` : `${ident('customerId')} = $${tenantIdx}`;
    const order = opts.orderBy ? ` ORDER BY ${opts.orderBy}` : '';
    const limit = opts.limit ? ` LIMIT ${Number(opts.limit)}` : '';
    return query<T>(`SELECT ${opts.columns ?? '*'} FROM ${ident(table)} WHERE ${where}${order}${limit}`, params);
  },
  async findOne<T = Record<string, unknown>>(
    table: string,
    opts: { columns?: string; where?: string; params?: readonly unknown[] } = {},
  ): Promise<T | null> {
    const rows = await this.findMany<T>(table, { ...opts, limit: 1 });
    return rows[0] ?? null;
  },
  async count(table: string, opts: { where?: string; params?: readonly unknown[] } = {}): Promise<number> {
    const rows = await this.findMany<{ n: string }>(table, { columns: 'COUNT(*)::int AS n', where: opts.where, params: opts.params });
    return (rows[0]?.n as unknown as number) ?? 0;
  },
  // DELETE ... WHERE (<where>) AND customerId=<tenant>. Returns rows deleted.
  async deleteMany(table: string, opts: { where?: string; params?: readonly unknown[] } = {}): Promise<number> {
    const tenant = currentTenantId();
    const params = [...(opts.params ?? [])];
    const tenantIdx = params.length + 1;
    params.push(tenant);
    const where = opts.where ? `(${opts.where}) AND ${ident('customerId')} = $${tenantIdx}` : `${ident('customerId')} = $${tenantIdx}`;
    return execute(`DELETE FROM ${ident(table)} WHERE ${where}`, params);
  },
};
